"""
Pipeline Monitor module for the Agent Reliable Memory System (Stage 390).

Design Principles:
1. First Principles: deterministic rules, no model dependencies
2. Thread-safe using threading.RLock
3. Global singleton via get_pipeline_monitor() with double-checked locking
4. Use Python dataclasses for data structures, Enum for types
5. Minimal dependencies, no circular dependencies
"""

from __future__ import annotations

import threading
import time
import uuid
from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum, auto
from typing import Any, Dict, List, Optional


class MetricType(Enum):
    """Enumeration of supported pipeline metric types."""

    THROUGHPUT = auto()
    LATENCY = auto()
    ERROR_RATE = auto()
    QUEUE_DEPTH = auto()
    RESOURCE_USAGE = auto()


class AlertLevel(Enum):
    """Enumeration of alert severity levels."""

    INFO = auto()
    WARNING = auto()
    CRITICAL = auto()


@dataclass
class PipelineMetric:
    """Represents a single recorded pipeline metric."""

    metric_id: str
    pipeline_id: str
    metric_type: MetricType
    value: float
    timestamp: datetime = field(default_factory=datetime.utcnow)
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class PipelineAlert:
    """Represents an alert generated by the pipeline monitor."""

    alert_id: str
    pipeline_id: str
    metric_type: MetricType
    level: AlertLevel
    message: str
    timestamp: datetime = field(default_factory=datetime.utcnow)
    acknowledged: bool = False


class PipelineMonitor:
    """
    Thread-safe pipeline monitor for metrics collection, alerting,
    health scoring, and statistics aggregation.

    Features:
    - Automatic alert generation when thresholds are exceeded.
    - Health score calculation based on error rate and latency.
    - Metric retention with a maximum of 10,000 metrics per pipeline.
    """

    # Maximum number of metrics retained per pipeline
    MAX_METRICS_PER_PIPELINE: int = 10000

    def __init__(self) -> None:
        """Initialize the PipelineMonitor."""
        self._metrics: List[PipelineMetric] = []
        self._alerts: List[PipelineAlert] = []
        self._thresholds: Dict[MetricType, Dict[str, float]] = {
            metric_type: {"WARNING": float("inf"), "CRITICAL": float("inf")}
            for metric_type in MetricType
        }
        self._lock: threading.RLock = threading.RLock()

    # ------------------------------------------------------------------
    # Metric recording and retrieval
    # ------------------------------------------------------------------

    def record_metric(
        self,
        pipeline_id: str,
        metric_type: MetricType,
        value: float,
        metadata: Optional[Dict[str, Any]] = None,
    ) -> str:
        """
        Record a new metric and evaluate thresholds for alert generation.

        Args:
            pipeline_id: Identifier of the pipeline.
            metric_type: Type of the metric.
            value: Numeric value of the metric.
            metadata: Optional metadata dictionary.

        Returns:
            The generated metric_id.
        """
        metric_id = str(uuid.uuid4())
        metric = PipelineMetric(
            metric_id=metric_id,
            pipeline_id=pipeline_id,
            metric_type=metric_type,
            value=value,
            metadata=metadata or {},
        )

        with self._lock:
            self._metrics.append(metric)
            self._enforce_retention(pipeline_id)
            self._evaluate_threshold(metric)

        return metric_id

    def get_metrics(
        self,
        pipeline_id: str,
        metric_type: Optional[MetricType] = None,
        start_time: Optional[datetime] = None,
        end_time: Optional[datetime] = None,
    ) -> List[PipelineMetric]:
        """
        Retrieve metrics filtered by pipeline, type, and time range.

        Args:
            pipeline_id: Identifier of the pipeline.
            metric_type: Optional metric type filter.
            start_time: Optional start time (inclusive).
            end_time: Optional end time (inclusive).

        Returns:
            A list of matching PipelineMetric objects.
        """
        with self._lock:
            results: List[PipelineMetric] = []
            for metric in self._metrics:
                if metric.pipeline_id != pipeline_id:
                    continue
                if metric_type is not None and metric.metric_type != metric_type:
                    continue
                if start_time is not None and metric.timestamp < start_time:
                    continue
                if end_time is not None and metric.timestamp > end_time:
                    continue
                results.append(metric)
            return results

    def get_latest_metric(
        self, pipeline_id: str, metric_type: MetricType
    ) -> Optional[PipelineMetric]:
        """
        Retrieve the most recent metric for a pipeline and metric type.

        Args:
            pipeline_id: Identifier of the pipeline.
            metric_type: Type of the metric.

        Returns:
            The latest PipelineMetric if found, else None.
        """
        with self._lock:
            candidates = [
                m
                for m in self._metrics
                if m.pipeline_id == pipeline_id and m.metric_type == metric_type
            ]
            if not candidates:
                return None
            return max(candidates, key=lambda m: m.timestamp)

    # ------------------------------------------------------------------
    # Threshold and alert management
    # ------------------------------------------------------------------

    def set_threshold(
        self, metric_type: MetricType, warning_level: float, critical_level: float
    ) -> bool:
        """
        Set WARNING and CRITICAL thresholds for a metric type.

        Args:
            metric_type: The metric type to configure.
            warning_level: Threshold value for WARNING alerts.
            critical_level: Threshold value for CRITICAL alerts.

        Returns:
            True if thresholds were set successfully.
        """
        with self._lock:
            self._thresholds[metric_type] = {
                "WARNING": warning_level,
                "CRITICAL": critical_level,
            }
            return True

    def check_alerts(self, pipeline_id: str) -> List[PipelineAlert]:
        """
        Retrieve unacknowledged alerts for a specific pipeline.

        Args:
            pipeline_id: Identifier of the pipeline.

        Returns:
            A list of unacknowledged PipelineAlert objects.
        """
        with self._lock:
            return [
                alert
                for alert in self._alerts
                if alert.pipeline_id == pipeline_id and not alert.acknowledged
            ]

    def acknowledge_alert(self, alert_id: str) -> bool:
        """
        Acknowledge an alert by its ID.

        Args:
            alert_id: The alert identifier.

        Returns:
            True if the alert was found and acknowledged, False otherwise.
        """
        with self._lock:
            for alert in self._alerts:
                if alert.alert_id == alert_id:
                    alert.acknowledged = True
                    return True
            return False

    def get_alerts(
        self,
        pipeline_id: Optional[str] = None,
        level: Optional[AlertLevel] = None,
        acknowledged: Optional[bool] = None,
    ) -> List[PipelineAlert]:
        """
        Retrieve alerts with optional filters.

        Args:
            pipeline_id: Optional pipeline identifier filter.
            level: Optional alert level filter.
            acknowledged: Optional acknowledged status filter.

        Returns:
            A list of matching PipelineAlert objects.
        """
        with self._lock:
            results: List[PipelineAlert] = []
            for alert in self._alerts:
                if pipeline_id is not None and alert.pipeline_id != pipeline_id:
                    continue
                if level is not None and alert.level != level:
                    continue
                if acknowledged is not None and alert.acknowledged != acknowledged:
                    continue
                results.append(alert)
            return results

    # ------------------------------------------------------------------
    # Statistics and health scoring
    # ------------------------------------------------------------------

    def get_statistics(self, pipeline_id: str) -> Dict[str, Any]:
        """
        Retrieve aggregated statistics for a pipeline.

        Args:
            pipeline_id: Identifier of the pipeline.

        Returns:
            A dictionary containing statistics per metric type.
        """
        with self._lock:
            stats: Dict[str, Any] = {}
            for metric_type in MetricType:
                values = [
                    m.value
                    for m in self._metrics
                    if m.pipeline_id == pipeline_id and m.metric_type == metric_type
                ]
                if values:
                    stats[metric_type.name] = {
                        "count": len(values),
                        "min": min(values),
                        "max": max(values),
                        "avg": sum(values) / len(values),
                        "latest": values[-1],
                    }
                else:
                    stats[metric_type.name] = {
                        "count": 0,
                        "min": None,
                        "max": None,
                        "avg": None,
                        "latest": None,
                    }
            stats["total_metrics"] = sum(
                1 for m in self._metrics if m.pipeline_id == pipeline_id
            )
            stats["total_alerts"] = sum(
                1 for a in self._alerts if a.pipeline_id == pipeline_id
            )
            return stats

    def get_health_score(self, pipeline_id: str) -> float:
        """
        Calculate a health score for a pipeline (0-100).

        The score is based on error rate and latency:
        - Lower error rates and latencies yield higher scores.
        - If no metrics are available, returns 100.0.

        Args:
            pipeline_id: Identifier of the pipeline.

        Returns:
            A float between 0.0 and 100.0.
        """
        with self._lock:
            error_metrics = [
                m.value
                for m in self._metrics
                if m.pipeline_id == pipeline_id
                and m.metric_type == MetricType.ERROR_RATE
            ]
            latency_metrics = [
                m.value
                for m in self._metrics
                if m.pipeline_id == pipeline_id
                and m.metric_type == MetricType.LATENCY
            ]

            if not error_metrics and not latency_metrics:
                return 100.0

            # Error rate component: 0% error -> 50 points, 100% error -> 0 points
            error_score = 50.0
            if error_metrics:
                avg_error = sum(error_metrics) / len(error_metrics)
                error_score = max(0.0, 50.0 - (avg_error * 50.0))

            # Latency component: 0ms -> 50 points, latency >= 1000ms -> 0 points
            latency_score = 50.0
            if latency_metrics:
                avg_latency = sum(latency_metrics) / len(latency_metrics)
                latency_score = max(0.0, 50.0 - (avg_latency / 1000.0 * 50.0))

            return min(100.0, max(0.0, error_score + latency_score))

    # ------------------------------------------------------------------
    # Cleanup
    # ------------------------------------------------------------------

    def clear_metrics(self, pipeline_id: Optional[str] = None) -> int:
        """
        Clear metrics, optionally filtered by pipeline.

        Args:
            pipeline_id: Optional pipeline identifier. If None, clears all metrics.

        Returns:
            Number of metrics removed.
        """
        with self._lock:
            if pipeline_id is None:
                count = len(self._metrics)
                self._metrics = []
                return count

            original_count = len(self._metrics)
            self._metrics = [
                m for m in self._metrics if m.pipeline_id != pipeline_id
            ]
            return original_count - len(self._metrics)

    def clear_alerts(self, pipeline_id: Optional[str] = None) -> int:
        """
        Clear alerts, optionally filtered by pipeline.

        Args:
            pipeline_id: Optional pipeline identifier. If None, clears all alerts.

        Returns:
            Number of alerts removed.
        """
        with self._lock:
            if pipeline_id is None:
                count = len(self._alerts)
                self._alerts = []
                return count

            original_count = len(self._alerts)
            self._alerts = [
                a for a in self._alerts if a.pipeline_id != pipeline_id
            ]
            return original_count - len(self._alerts)

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _enforce_retention(self, pipeline_id: str) -> None:
        """
        Enforce the maximum metric retention limit for a pipeline.

        Must be called while holding self._lock.
        """
        pipeline_metrics = [
            (idx, m)
            for idx, m in enumerate(self._metrics)
            if m.pipeline_id == pipeline_id
        ]
        if len(pipeline_metrics) > self.MAX_METRICS_PER_PIPELINE:
            # Remove oldest metrics (those with the earliest timestamps)
            pipeline_metrics.sort(key=lambda item: item[1].timestamp)
            to_remove = len(pipeline_metrics) - self.MAX_METRICS_PER_PIPELINE
            indices_to_remove = {item[0] for item in pipeline_metrics[:to_remove]}
            self._metrics = [
                m for idx, m in enumerate(self._metrics) if idx not in indices_to_remove
            ]

    def _evaluate_threshold(self, metric: PipelineMetric) -> None:
        """
        Evaluate a metric against configured thresholds and generate alerts.

        Must be called while holding self._lock.
        """
        thresholds = self._thresholds.get(metric.metric_type)
        if thresholds is None:
            return

        critical_level = thresholds.get("CRITICAL", float("inf"))
        warning_level = thresholds.get("WARNING", float("inf"))

        if metric.value >= critical_level:
            self._create_alert(metric, AlertLevel.CRITICAL)
        elif metric.value >= warning_level:
            self._create_alert(metric, AlertLevel.WARNING)

    def _create_alert(self, metric: PipelineMetric, level: AlertLevel) -> None:
        """
        Create and store a new alert.

        Must be called while holding self._lock.
        """
        alert = PipelineAlert(
            alert_id=str(uuid.uuid4()),
            pipeline_id=metric.pipeline_id,
            metric_type=metric.metric_type,
            level=level,
            message=(
                f"{metric.metric_type.name} exceeded {level.name} threshold "
                f"with value {metric.value}"
            ),
        )
        self._alerts.append(alert)


# ------------------------------------------------------------------------------
# Global singleton with double-checked locking
# ------------------------------------------------------------------------------

_singleton_instance: Optional[PipelineMonitor] = None
_singleton_lock: threading.Lock = threading.Lock()


def get_pipeline_monitor() -> PipelineMonitor:
    """
    Return the global PipelineMonitor singleton.

    Uses double-checked locking for thread-safe initialization.
    """
    global _singleton_instance
    if _singleton_instance is None:
        with _singleton_lock:
            if _singleton_instance is None:
                _singleton_instance = PipelineMonitor()
    return _singleton_instance


def reset_pipeline_monitor() -> None:
    """
    Reset the global singleton instance.

    This is intended for testing only.
    """
    global _singleton_instance
    with _singleton_lock:
        _singleton_instance = None
